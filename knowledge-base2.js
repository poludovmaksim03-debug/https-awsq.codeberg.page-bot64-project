        subjectInfo.rules.forEach(rule => prompt += `- ${rule}\n`);

        prompt += '\nТипичные ошибки:\n';
        subjectInfo.commonMistakes.forEach(mistake => prompt += `- ${mistake}\n`);

        prompt += `\nЗадание для проверки:\n${text}\n\n`;
        prompt += 'Дай подробный разбор на русском языке согласно структуре:\n';
